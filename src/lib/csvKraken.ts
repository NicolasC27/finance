import type { Transaction } from './types';
import { tokenize, normalizeHeader } from './csvCore';
import { displaySymbol } from './kraken';

/**
 * Parser for « Kraken spot ledgers » exports (SPEC v14 §E).
 *
 * Real format (always quoted, comma delimiter, header):
 *   "txid","refid","time","type","subtype","aclass","subclass","asset",
 *   "wallet","amount","fee","balance"
 *
 * Types seen in real statements:
 *   - krakcard/spend            negative EUR (Krak card spending)
 *   - krakcard/cashbackreward   positive BTC (cashback of the spending)
 *   - earn/reward               positive BTC (earn rewards)
 *   - transfer/useraccounttransfer  EUR ± (transfer between Kraken accounts:
 *     Kraken ↔ Krak card — NOT the bank, which goes through deposit/withdrawal)
 *   - spend|receive/kardconversion  card conversion BTC → EUR
 *
 * Split rule:
 *   - EUR rows → regular budget Transactions (account 'kraken', source
 *     'kraken-csv') — they take part in v13 internal transfer pair detection
 *     (the label contains « KRAKEN »);
 *   - crypto rows → NOT budget transactions (non-EUR): they feed the ledger
 *     store (krakenLedger.svelte) — balances per asset, cumulated cashback,
 *     history for the chart.
 *
 * Labels: upper-case bank style + trailing txid (« KRAKEN CARTE
 * LAAAAA-BBBBB-CCCCCC »). The txid is REQUIRED for txKey uniqueness: two 1.00 €
 * spendings can share the same date AND amount (seen in real exports).
 * merchantKey (merchant.ts) recognises the « KRAKEN … » prefix and displays it
 * nicely without the identifier.
 */

/** A typed raw ledger row (shared with the ledger store). */
export interface KrakenLedgerEntry {
	/** Unique row id (deduplicates re-imports). */
	txid: string;
	refid: string;
	/** Raw sortable timestamp « YYYY-MM-DD HH:MM:SS » (Kraken UTC). */
	at: string;
	/** Date only « YYYY-MM-DD » (booking/value date). */
	date: string;
	type: string;
	subtype: string;
	/** Display symbol (« BTC », « EUR »…). */
	asset: string;
	amount: number;
	fee: number;
	/** Asset balance AFTER the operation (balance column). */
	balance: number;
}

export interface KrakenLedgerParseResult {
	/** EUR transactions ready for the budget store. */
	transactions: Transaction[];
	/** Every row (EUR included — the balance column feeds the ledger). */
	entries: KrakenLedgerEntry[];
	ignored: number;
	errors: string[];
}

/** Expected normalised header (order imposed by Kraken). */
const EXPECTED_HEADER = [
	'txid',
	'refid',
	'time',
	'type',
	'subtype',
	'aclass',
	'subclass',
	'asset',
	'wallet',
	'amount',
	'fee',
	'balance'
];

/**
 * Kraken ledger format detection: the first 5 normalised columns are enough
 * (txid/refid/time/type/subtype) — no other known format starts this way.
 */
export function matchesKrakenLedgerHeader(headerFields: string[]): boolean {
	if (headerFields.length < 12) return false;
	const norm = headerFields.map(normalizeHeader);
	return EXPECTED_HEADER.slice(0, 5).every((h, i) => norm[i] === h);
}

/** Kraken amount « -5.9900 » (decimal point; scientific notation tolerated, « 3.8e-7 » from exports regenerated by the app) → number; null when invalid. */
function parseKrakenNumber(raw: string): number | null {
	const t = raw.trim();
	if (!/^-?\d+(\.\d+)?([eE][-+]?\d+)?$/.test(t)) return null;
	const n = Number(t);
	return Number.isFinite(n) ? n : null;
}

/** « 2026-06-01 07:22:21 » → ISO date « 2026-06-01 » (null when invalid). */
function krakenDate(raw: string): string | null {
	const m = /^(\d{4}-\d{2}-\d{2}) \d{2}:\d{2}:\d{2}$/.exec(raw.trim());
	return m ? m[1]! : null;
}

/**
 * Stable, deterministic label of an EUR row (the txid guarantees txKey
 * uniqueness; merchantKey hides the identifier on display). A transfer between
 * Kraken accounts (Kraken ↔ Krak card, not with the bank) keeps its historical
 * label: it is part of txKey (hidden rows, duplicates); readable display is
 * handled in merchant.ts (KRAKEN_LABELS).
 */
function ledgerLabel(entry: KrakenLedgerEntry): string {
	const kind = `${entry.type}/${entry.subtype}`;
	switch (kind) {
		case 'krakcard/spend':
			return `KRAKEN CARTE ${entry.txid}`;
		case 'transfer/useraccounttransfer':
			return `KRAKEN VIREMENT ${entry.amount >= 0 ? 'ENTREE' : 'SORTIE'} ${entry.txid}`;
		default:
			if (entry.subtype === 'kardconversion') return `KRAKEN CONVERSION CARTE ${entry.txid}`;
			return `KRAKEN ${entry.type.toUpperCase()} ${entry.txid}`;
	}
}

/**
 * Movement INTERNAL to wealth (neither spending nor income): fiat deposit or
 * withdrawal, bank ↔ Kraken transfer, EUR ↔ crypto trade, card conversion.
 * Hidden from the budget at import (counted in balances). Staying in the
 * budget: Kraken card spending (real spending) and EUR rewards. Only EUR rows
 * become budget transactions.
 */
export function isInternalKrakenMovement(entry: KrakenLedgerEntry): boolean {
	if (entry.asset !== 'EUR') return false;
	if (entry.type === 'deposit' || entry.type === 'withdrawal' || entry.type === 'transfer') return true;
	if (entry.type === 'trade' || entry.type === 'spend' || entry.type === 'receive') return true;
	if (entry.subtype === 'kardconversion') return true;
	return false;
}

/** EUR ledger row → budget transaction (« kraken » account); null for a crypto row. */
export function entryToTransaction(entry: KrakenLedgerEntry): Transaction | null {
	if (entry.asset !== 'EUR') return null;
	return {
		transaction_amount: { amount: Math.abs(entry.amount).toFixed(2), currency: 'EUR' },
		booking_date: entry.date,
		value_date: entry.date,
		remittance_information: [ledgerLabel(entry)],
		credit_debit_indicator: entry.amount >= 0 ? 'CRDT' : 'DBIT',
		source: 'kraken-csv',
		account: 'kraken'
	};
}

/** Parses the text of a Kraken ledger export (already UTF-8 decoded); only EUR rows become budget transactions. */
export function parseKrakenLedgerText(text: string): KrakenLedgerParseResult {
	const errors: string[] = [];
	const transactions: Transaction[] = [];
	const entries: KrakenLedgerEntry[] = [];
	let ignored = 0;

	const rows = tokenize(text, ',').filter((r) => r.some((f) => f.trim() !== ''));
	if (rows.length === 0) return { transactions, entries, ignored, errors: ['Fichier vide'] };
	if (!matchesKrakenLedgerHeader(rows[0]!)) {
		return {
			transactions,
			entries,
			ignored,
			errors: ['En-tête ledger Kraken introuvable (txid,refid,time,type,subtype… attendu)']
		};
	}

	for (let r = 1; r < rows.length; r++) {
		const f = rows[r]!;
		const lineNo = r + 1;
		const [txid = '', refid = '', time = '', type = '', subtype = '', , , assetRaw = '', , amountRaw = '', feeRaw = '0', balanceRaw = ''] =
			f.map((v) => v.trim());

		const date = krakenDate(time);
		const amount = parseKrakenNumber(amountRaw);
		const balance = parseKrakenNumber(balanceRaw);
		const fee = parseKrakenNumber(feeRaw) ?? 0;
		if (!txid || !date || amount === null || balance === null) {
			ignored++;
			errors.push(`Ligne ${lineNo} : ligne ledger illisible (txid/date/montant), ignorée`);
			continue;
		}

		const entry: KrakenLedgerEntry = {
			txid,
			refid,
			at: time,
			date,
			type: type.toLowerCase(),
			subtype: subtype.toLowerCase(),
			asset: displaySymbol(assetRaw.toUpperCase()),
			amount,
			fee,
			balance
		};
		entries.push(entry);

		const tx = entryToTransaction(entry);
		if (tx) transactions.push(tx);
	}

	return { transactions, entries, ignored, errors };
}
