import { normalizeLabelKey, KEEP_UPPER } from './format';

/**
 * Merchant extraction (SPEC v10 §1).
 *
 * Crédit Mutuel bank labels contain parts that change with every payment
 * (transaction date DDMM, card number, UIR reference…): a key learnt on the raw
 * label never matches again. `merchantKey` isolates the stable part — brand +
 * place — for learnt rules, the built-in dictionary and the bank → XLSX cross
 * learning.
 */

/** French technical prefixes removed at the start (repeated until stable). */
const PREFIX_RES: RegExp[] = [
	/^PAIEMENTS?( (CB|PSC|SEPA))?\s+/, // PAIEMENT CB 0105 … / PAIEMENT PSC 0908 …
	/^PRLV( SEPA)?\s+/, // PRLV SEPA PAYPAL …
	/^PRELEVEMENT\s+/,
	/^VIR( INST)?( SEPA)?( EMET)?\s+/, // VIR SEPA EMET … / VIR INST … (instant transfer)
	/^VIREMENT( SEPA)?\s+/,
	/^REM CHQ\s+/, // REM CHQ REF… (cheque deposit)
	/^REMISE CHEQUE\s+/,
	/^F COTIS\s+/, // F COTIS EUROCOMPTE CONFORT
	/^ECH PRET\s+/, // ECH PRET XXXX … (loan instalment)
	/^CB\s+/,
	/^CARTE KRAK\s+/, // CARTE KRAK EPICERIE DU PORT (Kraken statement, Krak card)
	/^RETRAIT( DAB)?\s+/,
	/^FRAIS\s+/,
	/^COM\s+/, // COM CARTE 1234 (fee)
	/^ANNULATION\s+/
];

/**
 * Noise tokens removed everywhere (order matters: the most specific patterns
 * first, generic numbers last).
 */
const NOISE_RES: RegExp[] = [
	/\b\d+[,.]\d{2}\s*(EUR|USD|GBP|CHF)\b/g, // amount in the original currency: « 108,00 EUR », « 12,00 USD » (card payments abroad)
	/\bPAY[A-Z0-9]{4}-[A-Z0-9]{6}-[A-Z0-9]{6}\b/g, // Krak card payment reference: PAYABCD-EFGHIJ-KL1M2N
	/\bCARTE \w+/g, // CARTE 1234 (card number, variable)
	/\bUIR\w+/g, // UIR0123456789012345 (interbank reference)
	/\bREF[\w-]+/g, // REF12345-67890
	/\bSEPA\b/g,
	/\bE\d{6,}\b/g, // E0000000001234567
	/\b[A-Z]*\d{6,}\w*\b/g, // long references: BF1234567, RMS1234…UI, 1234567890123
	/\b(?=[A-Z0-9]*\d)(?=[A-Z0-9]*[A-Z])[A-Z0-9]{10,}\b/g, // mixed alphanumeric references: CU1A23456B789012 (instant transfer)
	/\b\d{4}\b/g, // DDMM transaction dates (0908, 1108) of CM exports
	/\b\d[\d./-]*\b/g, // isolated numbers (00001, 10,00…)
	/\b(FR|FRA)\b$/ // country code at the end of the label
];

/** Generic fallback when the whole label was technical noise. */
const GENERIC_FALLBACK: [RegExp, string][] = [
	[/^REM CHQ\b|^REMISE CHEQUE\b/, 'REMISE CHEQUE'],
	[/^RETRAIT\b/, 'RETRAIT DAB'],
	[/^COM\b/, 'COMMISSION BANCAIRE'],
	[/^FRAIS\b/, 'FRAIS BANCAIRES']
];

/** Collapses spaces and turns punctuation into separators. */
function tidy(s: string): string {
	return s
		.replace(/[()*+/[\]_,.'°-]+/g, ' ')
		.replace(/\s+/g, ' ')
		.trim();
}

/**
 * Stable upper-case merchant key, for rules and grouping.
 * Pipeline: join → technical prefixes → noise tokens → deduplication (a token
 * repeated 3+ times IS the merchant, e.g. PAYPAL) → fallback when empty.
 *
 * The city is KEPT in the key (« VILLEFICTIVE EPICERIE DU PORT »): stable per
 * merchant + place, and inclusion matching (§2) links the variants.
 */
/**
 * Labels generated by the Kraken ledger import (v14): « KRAKEN CARTE
 * ABCDE1-FG2HI-JK3LMN » — the technical id (needed for txKey uniqueness) is
 * hidden: the merchant key is the readable label alone.
 */
const KRAKEN_LABELS: [RegExp, string][] = [
	[/^KRAKEN CARTE\b/, 'CARTE KRAKEN'],
	// transfer/useraccounttransfer: transfer between the Kraken account and the Krak card (not the bank)
	[/^KRAKEN VIREMENT ENTREE\b/, 'VIREMENT DEPUIS LA CARTE KRAK'],
	[/^KRAKEN VIREMENT SORTIE\b/, 'VIREMENT VERS LA CARTE KRAK'],
	[/^KRAKEN CONVERSION CARTE\b/, 'CONVERSION CARTE KRAKEN'],
	[/^KRAKEN \w+\b/, 'KRAKEN']
];

/** Label → key cache: merchantKey is called thousands of times per render (categories, rules, votes). */
const keyCache = new Map<string, string>();

export function merchantKey(remittanceInformation: string[]): string {
	const cacheKey = remittanceInformation.join('\u0001');
	const hit = keyCache.get(cacheKey);
	if (hit !== undefined) return hit;
	const key = computeMerchantKey(remittanceInformation);
	keyCache.set(cacheKey, key);
	return key;
}

/**
 * merchantKey pipeline:
 * 1. join the lines, upper-case, strip accents (Krak card labels such as
 *    « Garage Fictif ») and collapse spaces; Kraken ledger labels get a stable
 *    key without their technical id;
 * 2. remove technical prefixes at the start, until stable;
 * 3. remove noise tokens everywhere — dotted acronyms (« C.P.A.M. ») are
 *    joined first so punctuation normalisation doesn't split them into single
 *    letters; removing numbers can reveal another technical prefix
 *    (« 2 PAIEMENTS 2701 VILLEFICTIVE … »), which is removed in turn; mirrored
 *    labels (« VILLEFICTIVE HDV VILLEFICTIVE HDV ») keep one half; a token
 *    present 3+ times is the merchant itself (« PAYPAL (EUROPE) S.A R … PAYPAL
 *    VIREMENT … PAYPAL » → « PAYPAL »);
 * 4. empty result: a known generic label (cheque deposit, withdrawal), else
 *    the historical normalised key.
 */
function computeMerchantKey(remittanceInformation: string[]): string {
	let s = remittanceInformation
		.join(' ')
		.normalize('NFD')
		.replace(/[\u0300-\u036f]/g, '')
		.toUpperCase()
		.replace(/\s+/g, ' ')
		.trim();
	if (!s) return '';
	const raw = s;

	for (const [re, label] of KRAKEN_LABELS) {
		if (re.test(s)) return label;
	}

	let prev = '';
	while (prev !== s) {
		prev = s;
		for (const re of PREFIX_RES) s = s.replace(re, '');
	}

	for (const re of NOISE_RES) s = s.replace(re, ' ');
	s = s.replace(/\b(?:[A-Z]\.){2,}/g, (m) => m.replace(/\./g, ''));
	s = tidy(s);

	for (const re of PREFIX_RES) s = s.replace(re, '');
	s = tidy(s);

	const toks = s.split(' ');
	if (toks.length >= 4 && toks.length % 2 === 0) {
		const half = toks.length / 2;
		if (toks.slice(0, half).join(' ') === toks.slice(half).join(' ')) {
			s = toks.slice(0, half).join(' ');
		}
	}

	if (s) {
		const counts = new Map<string, number>();
		for (const tok of s.split(' ')) counts.set(tok, (counts.get(tok) ?? 0) + 1);
		let best: string | null = null;
		let bestCount = 0;
		for (const [tok, n] of counts) {
			if (n >= 3 && n > bestCount && tok.length >= 3) {
				best = tok;
				bestCount = n;
			}
		}
		if (best) return best;
	}

	if (!s) {
		for (const [re, label] of GENERIC_FALLBACK) {
			if (re.test(raw)) return label;
		}
		return normalizeLabelKey(remittanceInformation);
	}
	return s;
}

/**
 * Pretty display label (title case) of the merchant, for the prompt and the
 * RulesCard: « VILLEFICTIVE EPICERIE DU PORT » → « Villefictive Epicerie Du
 * Port ». The key is shown as is, just re-cased.
 */
export function merchantLabel(remittanceInformation: string[]): string {
	const key = merchantKey(remittanceInformation);
	if (!key) return '';
	return key
		.split(' ')
		.map((w) => {
			if (KEEP_UPPER.has(w)) return w;
			return w.charAt(0).toUpperCase() + w.slice(1).toLowerCase();
		})
		.join(' ');
}

/** Literal regex escaping. */
function escapeRegExp(s: string): string {
	return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Word-boundary inclusion (SPEC §2): `keyword` is contained in `key` with a
 * word boundary on each side (or equality). « EPICERIE DU PORT » matches
 * « VILLEFICTIVE EPICERIE DU PORT », not « EPICERIE DU PORTAIL ».
 */
const keywordRe = new Map<string, RegExp>();

export function keyIncludesKeyword(key: string, keyword: string): boolean {
	if (!key || !keyword) return false;
	if (key === keyword) return true;
	let re = keywordRe.get(keyword);
	if (!re) {
		re = new RegExp(`\\b${escapeRegExp(keyword)}\\b`);
		keywordRe.set(keyword, re);
	}
	return re.test(key);
}

/**
 * Normalised raw label (upper case, no accents, punctuation → spaces): base for
 * matching the tokens merchantKey damages — « CT 16 » (digits removed),
 * « CENTURY 21 », « REFERENCE AUTOMOBILES » (words starting with REF removed),
 * « VIREMENT SALAIRE » (prefix removed). Those tokens could never match.
 */
export function rawLabelKey(remittanceInformation: string[]): string {
	return remittanceInformation
		.join(' ')
		.normalize('NFD')
		.replace(/[\u0300-\u036f]/g, '')
		.toUpperCase()
		.replace(/[()*+/[\]_,.'°-]+/g, ' ')
		.replace(/\s+/g, ' ')
		.trim();
}

/** Precompiled dictionary token (one RegExp per token, created once). */
export interface CompiledToken<T> {
	token: string;
	value: T;
	re: RegExp;
	/** Token damaged by merchantKey: searched in the normalised raw label. */
	raw: boolean;
}

/**
 * Precompiles { value: tokens[] } dictionaries: each call used to recreate
 * ~400 RegExp (~85 µs per transaction, a full recategorisation on every
 * keystroke in « À trier »).
 */
export function compileTokens<T>(entries: [T, readonly string[]][]): CompiledToken<T>[] {
	const out: CompiledToken<T>[] = [];
	for (const [value, tokens] of entries) {
		for (const token of tokens) {
			const raw = merchantKey([token]) !== token;
			const norm = raw ? rawLabelKey([token]) : token;
			out.push({ token: norm, value, re: new RegExp(`\\b${escapeRegExp(norm)}\\b`), raw });
		}
	}
	return out;
}

/**
 * Longest token matching on word boundaries (merchant key, or raw label for
 * `raw` tokens); on equal length the first one wins. `accept` restricts the
 * candidate tokens (e.g. excluding generic words).
 */
export function longestToken<T>(
	compiled: readonly CompiledToken<T>[],
	key: string,
	raw = '',
	accept?: (t: CompiledToken<T>) => boolean
): CompiledToken<T> | undefined {
	let best: CompiledToken<T> | undefined;
	for (const t of compiled) {
		if (best && t.token.length <= best.token.length) continue;
		if (accept && !accept(t)) continue;
		const hay = t.raw ? raw : key;
		if (hay && (hay === t.token || t.re.test(hay))) best = t;
	}
	return best;
}
